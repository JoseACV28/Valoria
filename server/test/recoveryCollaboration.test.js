import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
process.env.SUPABASE_URL='';process.env.SUPABASE_ANON_KEY='';process.env.SUPABASE_SERVICE_ROLE_KEY='';
process.env.SITE_OWNER_ID='10000000-0000-4000-8000-000000000001';
const {default:app}=await import('../src/app.js');
const {demoUsers}=await import('../src/data/authStore.js');
const {demoStories,demoChapters,demoStoryReviews}=await import('../src/data/demoStore.js');
const {runAdminAction,listAdminAudit}=await import('../src/models/siteAdministration.js');
test('recuperación, colaboración y moderación respetan la autoría y conservan el contenido',async t=>{
 const server=app.listen(0,'127.0.0.1');await once(server,'listening');t.after(()=>new Promise(resolve=>server.close(resolve)));
 const base=`http://127.0.0.1:${server.address().port}/api`;
 async function req(route,token='',method='GET',body){const r=await fetch(base+route,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:`Bearer ${token}`}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,data:r.status===204?null:await r.json()};}
 const email=`${randomUUID()}@example.invalid`;
 await req('/auth/register','','POST',{email,password:'Testing-QA-2026-strong!',displayName:'Autor QA'});demoUsers.find(x=>x.email===email).id=process.env.SITE_OWNER_ID;
 const owner=(await req('/auth/login','','POST',{email,password:'Testing-QA-2026-strong!'})).data;
 const reader=(await req('/auth/register','','POST',{email:`${randomUUID()}@example.invalid`,password:'Testing-QA-2026-strong!',displayName:'Lector QA'})).data;
 const third=(await req('/auth/register','','POST',{email:`${randomUUID()}@example.invalid`,password:'Testing-QA-2026-strong!',displayName:'Otra cuenta QA'})).data;
 const token=owner.accessToken,rt=reader.accessToken,tt=third.accessToken;
 const story=(await req('/stories',token,'POST',{title:'Manuscrito privado',description:'Prueba',category:'Fantasia',status:'draft'})).data.story;
 assert.equal((await req('/reports',tt,'POST',{targetType:'story',targetId:story.id,reason:'No debe exponer un borrador'})).status,404);
 const chapter=(await req(`/stories/${story.id}/chapters`,token,'POST',{title:'Inicio',content:'Texto intacto',chapterNumber:1,status:'draft'})).data.chapter;
 assert.equal((await req(`/recovery/export/${story.id}`,rt)).status,403);
 assert.equal((await req(`/recovery/export/${story.id}`,token)).data.chapters[0].content,'Texto intacto');
 const invitation=(await req('/collaborations',token,'POST',{recipientId:reader.user.id,workType:'story',workId:story.id,role:'Lectura beta'})).data.id;
 assert.equal((await req(`/collaborations/${invitation}/manuscript`,rt)).status,404);
 assert.equal((await req(`/collaborations/${invitation}`,tt,'PATCH',{status:'accepted'})).status,403);
 assert.equal((await req(`/collaborations/${invitation}`,rt,'PATCH',{status:'accepted'})).status,200);
 assert.equal((await req(`/collaborations/${invitation}/manuscript`,rt)).status,403);
 assert.equal((await req(`/collaborations/${invitation}/access`,rt,'PUT',{access:'suggest'})).status,403);
 assert.equal((await req(`/collaborations/${invitation}/access`,token,'PUT',{access:'read'})).status,200);
 assert.equal((await req(`/collaborations/${invitation}/manuscript`,tt)).status,404);
 assert.equal((await req(`/collaborations/${invitation}/manuscript`,rt)).data.chapters[0].content,'Texto intacto');
 const suggestion={chapterId:chapter.id,quote:'Texto',note:'Una observación de prueba'};
 assert.equal((await req(`/collaborations/${invitation}/suggestions`,rt,'POST',suggestion)).status,403);
 await req(`/collaborations/${invitation}/access`,token,'PUT',{access:'suggest'});
 assert.equal((await req(`/collaborations/${invitation}/suggestions`,rt,'POST',suggestion)).status,201);
 const manuscript=(await req(`/collaborations/${invitation}/manuscript`,token)).data;
 assert.equal(manuscript.chapters[0].content,'Texto intacto');
 assert.equal((await req(`/collaborations/${invitation}/suggestions/${manuscript.suggestions[0].id}`,rt,'PATCH',{status:'reviewed'})).status,403);
 assert.equal((await req(`/stories/${story.id}/chapters/${chapter.id}`,rt,'PUT',{title:'Alterado',chapterNumber:1,status:'published'})).status,403);
 await req(`/collaborations/${invitation}/access`,token,'PUT',{access:'none'});
 assert.equal((await req(`/collaborations/${invitation}/manuscript`,rt)).status,403);
 await req(`/stories/${story.id}/chapters/${chapter.id}`,token,'PUT',{title:'Inicio',chapterNumber:1,content:'Texto intacto',status:'published'});
 const review=(await req(`/stories/${story.id}/reviews`,rt,'POST',{rating:5,reviewText:'Reseña que se conserva',chapterId:chapter.id})).data.review;
 assert.equal((await req(`/stories/${story.id}/chapters/${chapter.id}`,token,'DELETE')).status,204);
 assert.equal((await req(`/stories/${story.id}/chapters/${chapter.id}`,token,'PUT',{title:'Alterado',chapterNumber:1,status:'published'})).status,404);
 assert.equal((await req(`/stories/${story.id}/chapters`,token)).data.nextChapterNumber,2);
 assert.equal((await req(`/recovery/chapter/${chapter.id}/restore`,rt,'POST')).status,404);
 assert.equal((await req(`/recovery/chapter/${chapter.id}/restore`,token,'POST')).status,200);
 assert.equal(demoChapters.find(x=>x.id===chapter.id).status,'draft');
 assert.ok(demoStoryReviews.some(x=>x.id===review.id));
 assert.equal((await req(`/stories/${story.id}`,token,'DELETE')).status,204);
 assert.equal((await req(`/stories/${story.id}`)).status,404);
 assert.equal((await req('/recovery',rt)).data.items.length,0);
 assert.ok((await req('/recovery',token)).data.items.some(x=>x.id===story.id));
 assert.equal((await req(`/recovery/story/${story.id}/restore`,token,'POST')).status,200);
 assert.equal(demoStories.find(x=>x.id===story.id).status,'draft');
 assert.ok(demoStoryReviews.some(x=>x.id===review.id));
 await req(`/stories/${story.id}`,token,'PATCH',{status:'published'});
 const report=(await req('/reports',rt,'POST',{targetType:'story',targetId:story.id,reason:'Denuncia ficticia de prueba'})).data;
 assert.equal((await req(`/reports/${report.id}/target`,rt)).status,403);
 assert.equal((await req(`/reports/${report.id}/target`,token)).status,200);
 assert.equal((await req(`/reports/${report.id}/visibility`,token,'PUT',{hidden:true,reason:'Ocultamiento ficticio QA'})).status,200);
 assert.equal((await req(`/stories/${story.id}`)).status,404);
 assert.equal((await req(`/stories/${story.id}`,token)).status,200);
 assert.equal((await req(`/reports/${report.id}/visibility`,token,'PUT',{hidden:false,reason:'Restauración ficticia QA'})).status,200);
 await assert.rejects(runAdminAction(owner.user.id,'qa.failure','fixture',{},()=>{throw new Error('Simulated failure');}));
 assert.ok((await listAdminAudit()).some(x=>x.action==='qa.failure'&&x.outcome==='failed'));
 await req(`/stories/${story.id}`,token,'DELETE');demoStories.find(x=>x.id===story.id).deleted_at=new Date(Date.now()-31*86400000).toISOString();
 assert.equal((await req(`/recovery/story/${story.id}/restore`,token,'POST')).status,410);
});
